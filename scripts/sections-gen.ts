/**
 * `bun run sections:gen` — writes every section registry from the folders in
 * `src/sections/`.
 *
 * A section is one folder, `src/sections/<name>/`, named exactly as its schema
 * `_type`. This script reads the folders and writes the five registries the rest
 * of the app imports, so adding a section never means editing a shared file:
 *
 * - `schemas.generated.ts`      `sectionTypes`, for the Studio schema
 * - `fragments.generated.ts`    `SECTION_FRAGMENTS`, interpolated into `PAGE_QUERY`
 *   (via one `<name>.fragment.generated.ts` per section; see `render`)
 * - `components.generated.ts`   `SECTION_COMPONENTS`, for `SectionRenderer`
 * - `serializers.generated.ts`  `SECTION_SERIALIZERS`, for the GEO layer's `sectionToMarkdown`
 * - `dynamic.generated.ts`      `DYNAMIC_SECTION_TYPES`, for `hasDynamicParams`
 *
 * The output is gitignored and deterministic. Each registry imports only the
 * file kind it needs, so the import boundaries of the old hand-written registries
 * still hold: the fragments reach no Studio code, and `DYNAMIC_SECTION_TYPES` is
 * a literal that imports nothing at all.
 */
import {
	existsSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from 'node:fs';
import { join } from 'node:path';
import type { SectionConfig } from '@/types';

const SECTIONS_DIR = join(import.meta.dir, '..', 'src', 'sections');
const SECTION_NAME = /^[a-z][a-zA-Z0-9]*$/;
const REQUIRED_FILES = ['schema.ts', 'fragment.ts', 'markdown.ts'];
const HEADER =
	'// Generated by `bun run sections:gen` from src/sections/*/. Do not edit.\n';

type Section = { name: string; component: string } & SectionConfig;

/**
 * Upper-cases the first character: `heroSection` -> `HeroSection`.
 *
 * @param name - A camelCase section name.
 * @returns The PascalCase component name.
 */
const pascal = (name: string): string =>
	name.charAt(0).toUpperCase() + name.slice(1);

/**
 * Lists the problems with one section folder, so every broken folder is reported
 * in one run rather than one per run.
 *
 * @param name - The folder name.
 * @returns Human-readable problems; empty when the folder is complete.
 */
function folderProblems(name: string): string[] {
	if (!SECTION_NAME.test(name)) {
		return [
			`src/sections/${name}/: the folder name must be the camelCase schema _type, e.g. heroSection`,
		];
	}
	return [...REQUIRED_FILES, `${pascal(name)}.tsx`]
		.filter((file) => !existsSync(join(SECTIONS_DIR, name, file)))
		.map((file) => `src/sections/${name}/${file} is missing`);
}

/** The keys `config.ts` may set, each with its type check. */
const CONFIG_FIELDS: Record<string, (value: unknown) => boolean> = {
	dynamic: (value) => typeof value === 'boolean',
	order: Number.isFinite,
};

/**
 * Loads a section's optional `config.ts`, unvalidated.
 *
 * @param name - The section folder name.
 * @returns Its default export, or `{}` when the folder has no `config.ts`.
 */
async function loadConfig(name: string): Promise<unknown> {
	const path = join(SECTIONS_DIR, name, 'config.ts');
	return existsSync(path) ? (await import(path)).default : {};
}

/**
 * Lists the problems with a loaded `config.ts`: a missing default export, an
 * unknown key (a typo such as `dyanmic` would otherwise be ignored), or a value
 * of the wrong type.
 *
 * @param name - The section folder name.
 * @param config - The loaded default export.
 * @returns Human-readable problems; empty when the config is valid.
 */
function configProblems(name: string, config: unknown): string[] {
	const file = `src/sections/${name}/config.ts`;
	if (typeof config !== 'object' || config === null) {
		return [`${file} must default-export an object`];
	}
	return Object.entries(config).flatMap(([key, value]) => {
		const isValid = CONFIG_FIELDS[key];
		if (!isValid) return [`${file}: unknown key "${key}"`];
		return isValid(value) ? [] : [`${file}: "${key}" has the wrong type`];
	});
}

/**
 * Orders sections for the Studio insert menu by `order`, unordered ones last.
 * Applied to a name-sorted list with a stable sort, so ties stay in name order.
 *
 * @param a - First section.
 * @param b - Second section.
 * @returns A sort comparator result.
 */
const byInsertOrder = (a: Section, b: Section): number =>
	// MAX_VALUE rather than Infinity: Infinity - Infinity is NaN, which breaks the sort.
	(a.order ?? Number.MAX_VALUE) - (b.order ?? Number.MAX_VALUE);

/**
 * Renders the five registry modules.
 *
 * @param sections - Every section, sorted by name.
 * @returns File name -> file contents.
 */
function render(sections: Section[]): Record<string, string> {
	const imports = (
		file: (s: Section) => string,
		local: (s: Section) => string,
	) =>
		sections
			.map((s) => `import ${local(s)} from './${s.name}/${file(s)}';\n`)
			.join('');
	const entries = sections.map((s) => `\t${s.name},\n`).join('');
	const inMenuOrder = sections.toSorted(byInsertOrder).map((s) => s.name);
	const fragments = sections.map((s) => `\${${s.name}}`).join(',');
	const dynamic = sections.filter((s) => s.dynamic).map((s) => `'${s.name}'`);

	return {
		'schemas.generated.ts': `${HEADER}${imports(
			() => 'schema',
			(s) => s.name,
		)}
/** Section schema types, in Studio insert-menu order (\`config.ts\` \`order\`, then name). */
export const sectionTypes = [${inMenuOrder.join(', ')}];
`,
		// TypeGen resolves an import by its *local* name, so `{ fragment as hero }`
		// fails and every section's `fragment` collides in one module. Each one is
		// renamed in a module of its own first, which TypeGen can follow.
		...Object.fromEntries(
			sections.map((s) => [
				`${s.name}.fragment.generated.ts`,
				`${HEADER}import { fragment } from './${s.name}/fragment';\n\nexport const ${s.name} = fragment;\n`,
			]),
		),
		'fragments.generated.ts': `${HEADER}${sections
			.map(
				(s) => `import { ${s.name} } from './${s.name}.fragment.generated';\n`,
			)
			.join('')}
/** Every section's GROQ fragment, comma-joined, for the \`sections[]\` projection in \`PAGE_QUERY\`. */
export const SECTION_FRAGMENTS = \`${fragments}\`;
`,
		'components.generated.ts': `${HEADER}${imports(
			(s) => s.component,
			(s) => s.component,
		)}
/** Section components keyed by \`_type\`. \`SectionRenderer\` looks them up here. */
export const SECTION_COMPONENTS = {
${sections.map((s) => `\t${s.name}: ${s.component},\n`).join('')}};
`,
		'serializers.generated.ts': `${HEADER}import type { SectionSerializers } from '@/lib/markdown/sections';
${imports(
	() => 'markdown',
	(s) => s.name,
)}
/** Markdown serializers keyed by \`_type\`, one per section folder's \`markdown.ts\`. Read by \`sectionToMarkdown\`. */
export const SECTION_SERIALIZERS: SectionSerializers = {
${entries}};
`,
		'dynamic.generated.ts': `${HEADER}
/** Section types that read \`searchParams\` (\`config.ts\` \`dynamic: true\`). */
export const DYNAMIC_SECTION_TYPES: readonly string[] = [${dynamic.join(', ')}];
`,
	};
}

/**
 * Writes a file only when its contents changed, so a no-op run does not wake the
 * dev server's file watcher.
 *
 * @param path - Absolute file path.
 * @param contents - The new contents.
 */
function writeIfChanged(path: string, contents: string): void {
	if (existsSync(path) && readFileSync(path, 'utf8') === contents) return;
	writeFileSync(path, contents);
}

const names = readdirSync(SECTIONS_DIR, { withFileTypes: true })
	.filter((entry) => entry.isDirectory())
	.map((entry) => entry.name)
	.sort();

const configs = await Promise.all(names.map(loadConfig));
const problems = [
	...names.flatMap(folderProblems),
	...names.flatMap((name, index) => configProblems(name, configs[index])),
];
if (problems.length > 0) {
	console.error(`sections:gen: ${problems.length} problem(s)\n`);
	for (const problem of problems) console.error(`  - ${problem}`);
	process.exit(1);
}

const sections: Section[] = names.map((name, index) => ({
	name,
	component: pascal(name),
	...(configs[index] as SectionConfig),
}));

const output = render(sections);
for (const [file, contents] of Object.entries(output)) {
	writeIfChanged(join(SECTIONS_DIR, file), contents);
}
// A deleted section leaves its renamed fragment behind; drop it.
for (const file of readdirSync(SECTIONS_DIR)) {
	if (file.endsWith('.generated.ts') && !(file in output)) {
		rmSync(join(SECTIONS_DIR, file));
	}
}
